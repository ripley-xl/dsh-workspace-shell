// Restart orchestration for a Guest Web Host.
//
// Product rules are borrowed from dsh-restart-now (confirm, wait-for-idle,
// force, cooldown, receipt) and the mechanism from dshmarket's self-restart:
// a detached helper outlives this process, waits for it to go away, and replays
// the exact boot invocation.
//
// One deliberate difference: the replacement keeps the old port whenever it
// can, and only falls back to `--port 0`. DSH binds its login cookie to
// `127.0.0.1:<port>`, so a same-port restart keeps every open browser session
// working after a plain reload; a new port would force a new URL on the user.

import { mkdirSync, readFileSync, unlinkSync, writeFileSync, chmodSync, existsSync } from 'node:fs';
import { spawn as nodeSpawn } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import { tmpdir as nodeTmpdir } from 'node:os';

export const RESTART_ACK_TIMEOUT_MS = 8_000;
export const RESTART_COOLDOWN_MS = 5_000;
export const RESTART_WAIT_TICK_MS = 5_000;
export const RESTART_WAIT_MAX_MS = 30 * 60 * 1_000;
export const RECEIPT_NAME = '.workspace-host-restart.json';

const CODE = {
  disabled: 'HOST_RESTART_DISABLED',
  supervised: 'HOST_RESTART_SUPERVISED',
  busy: 'HOST_RESTART_BUSY',
  cooldown: 'HOST_RESTART_COOLDOWN',
  unavailable: 'HOST_RESTART_UNAVAILABLE',
};

export const restartError = (code) => Object.assign(new Error(code), { code, safe: true });

/** Same profile directory convention as the rest of the Guest package. */
export function receiptFile(profileDir) {
  if (typeof profileDir !== 'string' || !path.isAbsolute(profileDir)) throw restartError('HOST_RESTART_INVALID_PROFILE_DIR');
  return path.join(profileDir, RECEIPT_NAME);
}

/**
 * Point the replay at a concrete port. `--port 0` (the launcher's choice) would
 * mint a new origin on every restart, which is exactly what we are avoiding.
 */
export function rewritePort(argv, port) {
  if (!Array.isArray(argv) || argv.length === 0 || argv.some((part) => typeof part !== 'string')) {
    throw restartError('HOST_RESTART_INVALID_ARGV');
  }
  if (!Number.isInteger(port) || port < 0 || port > 65_535) throw restartError('HOST_RESTART_INVALID_PORT');
  const value = String(port);
  const out = [];
  let seen = false;
  for (let index = 0; index < argv.length; index += 1) {
    const part = argv[index];
    if (part === '--port') {
      out.push('--port', value);
      seen = true;
      if (index + 1 < argv.length) index += 1;
      continue;
    }
    if (part.startsWith('--port=')) {
      out.push(`--port=${value}`);
      seen = true;
      continue;
    }
    out.push(part);
  }
  if (!seen) out.push('--port', value);
  return out;
}

/** Reads the last restart outcome. A missing or corrupt receipt reads as null. */
export function readReceipt(file, { fs = { readFileSync, existsSync } } = {}) {
  try {
    if (!fs.existsSync(file)) return null;
    const value = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!value || typeof value !== 'object' || Array.isArray(value)) return null;
    return value.at && typeof value.at === 'string' ? value : null;
  } catch {
    return null;
  }
}

/** Milliseconds left before another restart is allowed; 0 when allowed. */
export function cooldownRemaining(receipt, nowMs = Date.now(), windowMs = RESTART_COOLDOWN_MS) {
  const at = typeof receipt?.at === 'string' ? Date.parse(receipt.at) : Number.NaN;
  if (!Number.isFinite(at)) return 0;
  const remaining = at + windowMs - nowMs;
  return remaining > 0 ? remaining : 0;
}

/**
 * The detached helper. Written as a plain script string (CommonJS) because it
 * runs under `process.execPath` in a process that must not share this one's
 * lifetime. The replacement announces itself on stdout exactly like a manually
 * launched Host — `dsh web: <url>` — which is the only signal that carries the
 * fresh login token.
 */
export function helperSource(payload) {
  const boot = {
    pid: payload.pid,
    port: payload.port,
    cwd: payload.cwd,
    env: payload.env,
    argvPort: payload.argvPort,
    argvEphemeral: payload.argvEphemeral,
    receipt: payload.receipt,
    ack: payload.ack,
    log: payload.log,
    hostLog: payload.hostLog,
  };
  return `// generated by dsh-workspace-guest: restart helper
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const net = require('node:net');
const boot = ${JSON.stringify(boot)};
try { fs.unlinkSync(process.argv[1]); } catch {}
const MAX_LINES = 64 * 1024;
const log = (line) => { try { fs.appendFileSync(boot.log, new Date().toISOString() + ' ' + line + '\\n'); } catch {} };
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
const alive = (pid) => { try { process.kill(pid, 0); return true; } catch { return false; } };
const receipt = (value) => {
  try {
    fs.writeFileSync(boot.receipt, JSON.stringify({ at: new Date().toISOString(), ...value }) + '\\n', { mode: 0o600 });
  } catch { /* the caller reports the failure on next boot */ }
};
const portFree = () => new Promise((resolve) => {
  const socket = net.connect({ host: '127.0.0.1', port: boot.port });
  const done = (free) => { socket.destroy(); resolve(free); };
  socket.once('connect', () => done(false));
  socket.once('error', () => done(true));
  socket.setTimeout(500, () => done(true));
});
// The replacement writes to a FILE, never to our pipes: once this helper exits,
// a pipe's read end is gone and the next console write would kill the Host with
// EPIPE. The file also keeps the startup diagnosis around after we are gone.
const launch = (argv, attempt) => new Promise((resolve) => {
  const hostLog = boot.hostLog + '.' + attempt;
  try { fs.writeFileSync(hostLog, '', { mode: 0o600 }); } catch {}
  let fd = 'ignore';
  try { fd = fs.openSync(hostLog, 'a', 0o600); } catch {}
  const child = spawn(argv[0], argv.slice(1), {
    cwd: boot.cwd, env: boot.env, detached: true, stdio: ['ignore', fd, fd], windowsHide: true,
  });
  if (typeof fd === 'number') { try { fs.closeSync(fd); } catch {} }
  let settled = false;
  const finish = (value) => { if (!settled) { settled = true; clearInterval(timer); clearTimeout(deadline); resolve(value); } };
  const tailOfLog = () => { try { return fs.readFileSync(hostLog, 'utf8').slice(-MAX_LINES); } catch { return ''; } };
  const read = () => {
    const match = /^dsh web: (\\S+)$/mu.exec(tailOfLog());
    if (match) finish({ ok: true, child, url: match[1] });
  };
  const timer = setInterval(read, 200);
  timer.unref?.();
  const deadline = setTimeout(() => finish({ ok: false, timeout: true, errors: tailOfLog().slice(-4096) }), 20000);
  deadline.unref?.();
  child.once('exit', (code) => finish({ ok: false, code, errors: tailOfLog().slice(-4096) }));
  child.once('error', (error) => finish({ ok: false, errors: String(error && error.message || error) }));
});
(async () => {
  try {
    fs.writeFileSync(boot.ack, JSON.stringify({ at: Date.now() }), { mode: 0o600 });
    log('ack');
    let waited = 0;
    while (alive(boot.pid) && waited < 2000) { await sleep(100); waited += 100; }
    if (alive(boot.pid)) { try { process.kill(boot.pid, 'SIGTERM'); } catch {} log('sigterm'); }
    waited = 0;
    while (alive(boot.pid) && waited < 4000) { await sleep(100); waited += 100; }
    if (alive(boot.pid)) { try { process.kill(boot.pid, 'SIGKILL'); } catch {} log('sigkill'); await sleep(300); }
    let freed = 0;
    while (!(await portFree()) && freed < 10000) { await sleep(200); freed += 200; }
    log('port freed after ' + freed + 'ms');
    let result = await launch(boot.argvPort, 'same-port');
    let attempts = 1;
    if (!result.ok) {
      log('same-port launch failed: ' + JSON.stringify({ code: result.code, timeout: result.timeout }));
      result = await launch(boot.argvEphemeral, 'ephemeral');
      attempts = 2;
    }
    if (!result.ok) {
      receipt({ ok: false, attempts, error: result.timeout ? 'TIMEOUT' : 'EXITED', detail: result.errors || '' });
      log('failed');
      process.exit(0);
    }
    try { result.child.unref(); } catch {}
    let port = boot.port;
    try { port = Number(new URL(result.url).port) || boot.port; } catch {}
    receipt({ ok: true, pid: result.child.pid, port, url: result.url, attempts });
    log('restarted pid=' + result.child.pid + ' port=' + port);
    process.exit(0);
  } catch (error) {
    receipt({ ok: false, error: 'HELPER_FAILED', detail: String(error && error.message || error) });
    process.exit(0);
  }
})();
`;
}

/** Filters the bits of this Host's environment that only made sense for its boot. */
export function restartEnvironment(env = process.env) {
  const out = {};
  for (const [key, value] of Object.entries(env)) {
    if (value === undefined) continue;
    if (key === 'DSH_SESSION_ID' || key === 'DSH_WEB_URL' || key === 'DSH_SHELL') continue;
    if (key === 'ELECTRON_RUN_AS_NODE') continue;
    out[key] = value;
  }
  return out;
}

export function restartPayload({ identity, receipt, ack, log }) {
  return {
    pid: identity.pid,
    port: identity.port,
    cwd: identity.cwd,
    env: identity.env ?? restartEnvironment(),
    argvPort: rewritePort(identity.argv, identity.port),
    argvEphemeral: rewritePort(identity.argv, 0),
    receipt,
    ack,
    log,
    hostLog: log + '.host',
  };
}

function privateDirectory(directory) {
  mkdirSync(directory, { recursive: true, mode: 0o700 });
  try { chmodSync(directory, 0o700); } catch { /* platforms without POSIX modes */ }
  return directory;
}

/**
 * @param {object} options
 * @param {string} options.profileDir
 * @param {{pid:number,port:number,url:string,argv:string[],cwd:string,env?:object}} options.identity
 * @param {() => {tasks:number, jobs:number}} options.busy
 * @param {(file:string, args:string[], options:object) => any} [options.spawn]
 * @param {string} [options.tmpdir]
 * @param {() => number} [options.now]
 * @param {boolean} [options.allowRestart]
 */
export function createHostRestart(options = {}) {
  const identity = options.identity;
  const profileDir = options.profileDir;
  if (!identity || !Number.isInteger(identity.pid) || !Number.isInteger(identity.port)) throw restartError('HOST_RESTART_INVALID_IDENTITY');
  const file = receiptFile(profileDir);
  const spawn = options.spawn ?? nodeSpawn;
  const now = options.now ?? Date.now;
  const busy = typeof options.busy === 'function' ? options.busy : () => ({ tasks: 0, jobs: 0 });
  const allowRestart = options.allowRestart !== false;
  const root = privateDirectory(path.join(options.tmpdir ?? nodeTmpdir(), 'dsh-workspace-host-restart'));
  const timers = options.timers ?? { setInterval, clearInterval, setTimeout };

  let lastDispatchAt = 0;
  const wait = { active: false, since: 0, deadline: 0, timer: null, last: null };
  let disposed = false;

  const lastDispatchCooldown = () => (lastDispatchAt ? Math.max(0, lastDispatchAt + RESTART_COOLDOWN_MS - now()) : 0);
  const snapshot = () => ({
    allowRestart,
    busy: (() => { try { return busy(); } catch { return { tasks: 0, jobs: 0 }; } })(),
    cooldownMs: Math.max(cooldownRemaining(readReceipt(file), now()), lastDispatchCooldown()),
    lastRestart: readReceipt(file),
    wait: wait.active ? { state: 'waiting', since: wait.since, remainingMs: Math.max(0, wait.deadline - now()) } : { state: 'idle' },
  });

  function cancel() {
    const wasActive = wait.active;
    if (wait.timer) { timers.clearInterval(wait.timer); wait.timer = null; }
    wait.active = false;
    wait.since = 0;
    wait.deadline = 0;
    wait.last = null;
    return wasActive;
  }

  function dispatch(mode) {
    const stamp = randomUUID().replaceAll('-', '').slice(0, 12);
    const helper = path.join(root, `${stamp}.helper.cjs`);
    const ack = path.join(root, `${stamp}.ack.json`);
    const log = path.join(root, `${stamp}.log`);
    const payload = restartPayload({ identity, receipt: file, ack, log });
    writeFileSync(helper, helperSource(payload), { mode: 0o600 });
    const child = spawn(process.execPath, [helper], {
      detached: true, stdio: 'ignore', windowsHide: true,
      env: { ...process.env, ELECTRON_RUN_AS_NODE: '1' },
    });
    try { child.unref?.(); } catch { /* detached already */ }
    lastDispatchAt = now();
    const deadline = now() + RESTART_ACK_TIMEOUT_MS;
    return (async () => {
      while (now() < deadline) {
        if (existsSync(ack)) {
          try { unlinkSync(ack); } catch { /* best effort */ }
          return { ok: true, mode, startedAt: new Date(lastDispatchAt).toISOString(), pid: child?.pid ?? null };
        }
        await new Promise((resolve) => timers.setTimeout(resolve, 50));
      }
      throw restartError(CODE.unavailable);
    })();
  }

  function startWait(mode) {
    if (wait.active) return { ok: true, mode: 'waiting', since: wait.since };
    wait.active = true;
    wait.since = now();
    wait.deadline = wait.since + RESTART_WAIT_MAX_MS;
    wait.last = snapshot().busy;
    const tick = async () => {
      if (!wait.active || disposed) return;
      const current = snapshot().busy;
      wait.last = current;
      const expired = now() >= wait.deadline;
      if (current.tasks + current.jobs > 0 && !expired) return;
      cancel();
      try { await dispatch(mode); } catch { /* the receipt or the next restart reports it */ }
    };
    wait.timer = timers.setInterval(() => { tick().catch(() => {}); }, RESTART_WAIT_TICK_MS);
    if (typeof wait.timer?.unref === 'function') wait.timer.unref();
    return { ok: true, mode: 'waiting', since: wait.since, remainingMs: Math.max(0, wait.deadline - now()) };
  }

  return Object.freeze({
    status: snapshot,
    async restart({ mode = 'now', force = false } = {}) {
      if (disposed) throw restartError(CODE.unavailable);
      if (!allowRestart) throw restartError(CODE.disabled);
      if (mode === 'cancel') return { ok: true, cancelled: cancel() };
      const remaining = Math.max(cooldownRemaining(readReceipt(file), now()), lastDispatchCooldown());
      if (remaining > 0) throw restartError(CODE.cooldown);
      const current = snapshot().busy;
      if (current.tasks + current.jobs > 0 && !force) {
        if (mode === 'wait') return startWait(mode);
        throw restartError(CODE.busy);
      }
      cancel();
      return dispatch(mode);
    },
    cancel,
    dispose() {
      if (disposed) return;
      disposed = true;
      cancel();
    },
  });
}
