import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';

const root = new URL('../packages/guest/', import.meta.url);
const outputFlag = process.argv.indexOf('--out-dir');
if (outputFlag >= 0 && (!process.argv[outputFlag + 1] || process.argv[outputFlag + 1].startsWith('--'))) throw new Error('--out-dir requires a directory');
const outputRoot = outputFlag < 0 ? root : pathToFileURL(resolve(process.argv[outputFlag + 1]) + sep);
// Same concatenated, import-free build as the host Client: the guest bundle
// shares the session-host Client sources with the host package.
const names = [
  'notification', 'cwd', 'clipboard', '../session-host/submissions', '../session-host/controller', '../session-host/ui', 'entry',
];
const modules = [];
for (const name of names) modules.push(await readFile(new URL('src/' + name + '.js', root), 'utf8'));
const exportedNames = (text) => [...text.matchAll(/^export (?:async )?(?:function|const|class) ([A-Za-z_$][\w$]*)/gm)].map((match) => match[1]);
const exportsByModule = modules.map(exportedNames);
const allExports = exportsByModule.flat();
const duplicateExports = [...new Set(allExports.filter((name, index) => allExports.indexOf(name) !== index))];
if (duplicateExports.length) throw new Error('Duplicate exported name across modules: ' + duplicateExports.join(', '));
const parts = modules.map((text, index) => {
  const body = text.replace(/^export /gm, '');
  const locals = exportsByModule[index];
  if (!locals.length) return `// ---- module: ${names[index]} ----\n(() => {\n${body}\n})();`;
  return `// ---- module: ${names[index]} ----\nconst m${index} = (() => {\n${body}\nreturn { ${locals.join(', ')} };\n})();\nconst { ${locals.join(', ')} } = m${index};`;
});
const source = parts.join('\n');
if (/^\s*(import|export)\s/m.test(source)) throw new Error('Unsupported runtime dependency');
const candidates = [
  'createSessionHostPlugin', 'createSessionHostClient', 'observeSessionSubmissions',
  'applyTransferredDraft', 'sessionHostCss', 'installGuestCwd', 'createGuestNotificationBridge',
];
const bindings = candidates.filter((name) => new RegExp('\\b' + name + '\\b').test(source));
const absent = candidates.filter((name) => !bindings.includes(name));
if (absent.length) throw new Error('Missing generated guest bindings: ' + absent.join(', '));
const built = "// Generated by scripts/build-guest-client.mjs; edit src instead.\nwindow.__ModuleLoader__.load({id:'dsh-workspace-guest',factory(require){\nconst React=require('react');\nconst primitives=require('@deepseek-ai/dsh-client-ui-primitives');\n" + source + '\nreturn createGuestPlugin(React,{' + bindings.join(',') + ',primitives,document,window});\n}});\n';
const target = new URL('client.js', outputRoot);
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8');
  if (current !== built) throw new Error('Guest Client artifact is stale: client.js');
} else {
  await mkdir(new URL('./', target), { recursive: true });
  await writeFile(target, built);
}
console.log(process.argv.includes('--check') ? 'Guest Client matches authored sources' : 'Built Guest Client');
