import { mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('../packages/shell/', import.meta.url);
const source = await readFile(new URL('src/notifications.js', root), 'utf8');
const body = source.replace(/^export /gm, '');
if (/^\s*(import|export)\s/m.test(body)) throw new Error('Guest notification companion must stay import-free');
const built = `// Generated by scripts/build-guest-notify.mjs; edit src/notifications.js instead.
window.__ModuleLoader__.load({
  id: 'dsh-workspace-shell-guest-notify',
  factory() {
    const mod = (() => {
${body}
return { createGuestNotificationBridge };
})();
    function apply(ctx) {
      const bridge = mod.createGuestNotificationBridge({ window, ctx });
      try { ctx.effect(() => () => bridge.dispose(), 'workspace guest notifications'); }
      catch { bridge.dispose(); }
    }
    return { inject: ['sessions', 'uiSession', 'uiWorkspace'], apply };
  },
});
`;
const target = new URL('guest-notify/client.js', root);
if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8');
  if (current !== built) throw new Error('Guest notification companion is stale: guest-notify/client.js');
} else {
  await mkdir(new URL('.', target), { recursive: true });
  await writeFile(target, built);
}
console.log(process.argv.includes('--check') ? 'Guest notification companion matches authored sources' : 'Built guest notification companion');
