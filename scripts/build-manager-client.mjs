import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = new URL('../packages/manager/', import.meta.url);
const flag = process.argv.indexOf('--out-dir');
if (flag >= 0 && (!process.argv[flag + 1] || process.argv[flag + 1].startsWith('--'))) throw new Error('--out-dir requires a directory');
const output = flag < 0 ? fileURLToPath(root) : resolve(process.argv[flag + 1]);
const modules = [];
for (const name of ['ssh-launcher', 'workspace-extension']) {
  const text = await readFile(new URL(`src/client/${name}.js`, root), 'utf8');
  const names = [...text.matchAll(/^export function (\w+)/gm)].map((match) => match[1]);
  const body = text.replace(/^export /gm, '');
  if (/^\s*(import|export)\s/m.test(body)) throw new Error('Unsupported component dependency');
  modules.push(`const { ${names.join(', ')} } = (() => {\n${body}\nreturn { ${names.join(', ')} };\n})();`);
}
const built = "// Generated by scripts/build-manager-client.mjs; edit src/client instead.\nwindow.__ModuleLoader__.load({id:'@local/dsh-ssh-remote',factory(require){\nconst React=require('react');\n"
  + modules.join('\n') + '\nreturn createSshComponentPlugin(React,{createSshLauncher,window,document});\n}});\n';
const target = resolve(output, 'client.js');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== built) throw new Error('SSH component Client is stale');
} else {
  await mkdir(output, { recursive: true });
  await writeFile(target, built);
}
console.log('SSH component Client matches authored sources');
