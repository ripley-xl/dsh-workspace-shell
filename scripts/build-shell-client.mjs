import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { resolve, sep } from 'node:path';
const require = createRequire(import.meta.url);
const root = new URL('../packages/shell/', import.meta.url);
const outputFlag = process.argv.indexOf('--out-dir');
if (outputFlag >= 0 && (!process.argv[outputFlag + 1] || process.argv[outputFlag + 1].startsWith('--'))) throw new Error('--out-dir requires a directory');
const outputRoot = outputFlag < 0 ? root : pathToFileURL(resolve(process.argv[outputFlag + 1]) + sep);
// Dependency order for the concatenated, import-free Client factory. Every module
// only declares functions/constants; cross-module calls happen at runtime, so this
// order is declaration order, not an ES module graph.
const names = [
  'adapter', 'geometry', 'tab-state', 'tab-controller', 'input-gate',
  'web-timing', 'desktop-guest', 'browser-guest', 'tui-provider',
  'chrome-tabs', 'workspace-client', 'launcher', 'styles', 'frame', 'entry',
  '../session-host/submissions', '../session-host/controller', '../session-host/ui',
];
const modules = [];
const missingModules = [];
for (const name of names) {
  try { modules.push(await readFile(new URL('src/' + name + '.js', root), 'utf8')); }
  catch (error) {
    if (error?.code === 'ENOENT') { missingModules.push(name); continue; }
    throw error;
  }
}
// Each module keeps its own top-level scope: separate modules legitimately reuse
// helper names (both Guest adapters declare ERROR_CODES, for example), and a flat
// concatenation would be a SyntaxError inside the real Client factory.
const exportedNames = (text) => [...text.matchAll(/^export (?:async )?(?:function|const|class) ([A-Za-z_$][\w$]*)/gm)].map((match) => match[1]);
const exportsByModule = modules.map(exportedNames);
const allExports = exportsByModule.flat();
const duplicateExports = [...new Set(allExports.filter((name, index) => allExports.indexOf(name) !== index))];
if (duplicateExports.length) throw new Error('Duplicate exported name across modules: ' + duplicateExports.join(', '));
const parts = modules.map((text, index) => {
  const body = text.replace(/^export /gm, '');
  const locals = exportsByModule[index];
  if (!locals.length) return `// ---- module: ${names[index]} ----\n(() => {\n${body}\n})();`;
  return `// ---- module: ${names[index]} ----\nconst m${index} = (() => {\n${body}\nreturn { ${locals.join(', ')} };\n})();\nconst { ${locals.join(', ')} } = m${index};`;
});
const source = parts.join('\n');
if (/^\s*(import|export)\s/m.test(source)) throw new Error('Unsupported runtime dependency');
// Each name below is a factory injected into createShellPlugin. A module that has
// not landed yet omits its binding; the entry code treats the missing dependency
// as an unavailable optional panel instead of failing to load.
const candidates = [
  'installFrameAdapter', 'createFrameViews', 'solveFrame', 'createPointerResize', 'shellCss',
  'createTabState', 'createTabController', 'installInputGate', 'createWebTiming',
  'createDesktopGuest', 'createBrowserGuest', 'createTuiProvider',
  'createChromeTabs', 'createWorkspaceClient', 'createLauncher',
  'createSessionHostPlugin', 'createSessionHostClient', 'observeSessionSubmissions',
  'applyTransferredDraft', 'sessionHostCss',
];
const optional = new Set();
const bindings = candidates.filter((name) => new RegExp('\\b' + name + '\\b').test(source));
const absent = candidates.filter((name) => !bindings.includes(name) && !optional.has(name));
if (absent.length) throw new Error('Missing generated bindings: ' + absent.join(', ') + (missingModules.length ? ' (absent modules: ' + missingModules.join(', ') + ')' : ''));
if (missingModules.length) console.warn('Optional Shell modules are absent: ' + missingModules.join(', '));
const built = "// Generated by scripts/build-shell-client.mjs; edit src instead.\nwindow.__ModuleLoader__.load({id:'@local/dsh-workspace-shell',factory(require){\nconst React=require('react');\nconst primitives=require('@deepseek-ai/dsh-client-ui-primitives');\n" + source + '\nreturn createShellPlugin(React,{' + bindings.join(',') + ',primitives,document,window});\n}});\n';
const xtermRoot = new URL('../', pathToFileURL(require.resolve('@xterm/xterm')));
const fitRoot = new URL('../', pathToFileURL(require.resolve('@xterm/addon-fit')));
for (const [directory, version] of [[xtermRoot, '6.0.0'], [fitRoot, '0.11.0']]) {
  if (JSON.parse(await readFile(new URL('package.json', directory), 'utf8')).version !== version) throw new Error('Unexpected terminal dependency version');
}
const terminalSource = await readFile(new URL('src/terminal-document.js', root), 'utf8');
const outputs = new Map([
  ['client.js', built],
  ['assets/xterm.js', await readFile(new URL('lib/xterm.js', xtermRoot))],
  ['assets/xterm.css', await readFile(new URL('css/xterm.css', xtermRoot))],
  ['assets/addon-fit.js', await readFile(new URL('lib/addon-fit.js', fitRoot))],
  ['assets/terminal-document.js', terminalSource.replace(/^export /gm, '') + '\nstartTerminalDocument(window,document);\n'],
  ['assets/LICENSE-xterm.txt', await readFile(new URL('LICENSE', xtermRoot))],
  ['assets/LICENSE-addon-fit.txt', await readFile(new URL('LICENSE', fitRoot))],
]);
for (const [name, value] of outputs) {
  const target = new URL(name, outputRoot);
  if (process.argv.includes('--check')) {
    if (!(await readFile(target)).equals(Buffer.from(value))) throw new Error('Workspace artifact is stale: ' + name);
  } else { await mkdir(new URL('./', target), { recursive: true }); await writeFile(target, value); }
}
console.log(process.argv.includes('--check') ? 'Workspace Client and terminal assets match authored sources' : 'Built workspace Client and terminal assets');
